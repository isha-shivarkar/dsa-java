public class arithmeticOperators{
    public static void main(String args[]){
        int a=10;
        int b=5;
        System.out.println("add:"+(a+b));
        System.out.println("subs:"+(a-b));
        System.out.println("div:"+(a/b));
        System.out.println("mul:"+(a*b));
        System.out.println("mod:"+(a%b));
    }
}